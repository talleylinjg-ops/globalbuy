export function inferCategory(keywords) {
  const text = (keywords || []).join(' ').toLowerCase();
  for (const [category, words] of CATEGORY_KEYWORDS) {
    for (const w of words) {
      if (text.includes(w.toLowerCase())) return category;
    }
  }
  return '默认';
}

export function estimateWeightGrams(category) {
  return CATEGORY_WEIGHTS_GRAMS[category] ?? DEFAULT_WEIGHT_GRAMS;
}
