// 简易关键词匹配（mock 搜索引擎）
export function mockSearch(keyword) {
  const kw = (keyword || '').toLowerCase().trim();
  if (!kw) return [];
  const terms = kw.split(/[\s,，]+/).filter((t) => t.length > 0);

  const scored = MOCK_PRODUCTS
    .map((p) => {
      const haystack = `${p.title} ${p.platform} ${p.shopName}`.toLowerCase();
      let hits = 0;
      for (const t of terms) {
        if (haystack.includes(t)) hits += 1;
      }
      return { ...p, _hits: hits, _score: hits / terms.length };
    })
    .filter((p) => p._hits > 0);

  // AND 语义优先：所有词都命中的排前面，避免搜索结果过宽
  scored.sort((a, b) => {
    if (b._hits !== a._hits) return b._hits - a._hits;
    return b._score - a._score;
  });

  const allHit = scored.filter((p) => p._hits >= terms.length);
  const pool = allHit.length >= 3 ? allHit : scored.filter((p) => p._hits >= Math.ceil(terms.length / 2) || terms.length === 1);

  return (pool.length ? pool : scored.slice(0, 8))
    .slice(0, 12)
    .map(({ _hits, _score, ...rest }) => rest);
}

